-- =============================================================================
-- JobTrack :: V1 - initial relational schema
--
-- Design notes
--  * All instants are stored as TIMESTAMPTZ (UTC on the wire) so that reminders
--    and interview times stay correct across time zones.
--  * Calendar-only values (applied_at, deadline, next_action_date) are DATE.
--  * Enum-like columns use VARCHAR + CHECK constraints: readable in SQL clients
--    and trivially extendable without a migration of a native enum type.
--  * Every child table cascades from its parent, so deleting a user or an
--    application can never leave orphans behind.
--  * Indexes mirror the filters exposed by GET /api/applications and the
--    aggregate queries used by the analytics endpoints.
-- =============================================================================

-- ---------------------------------------------------------------- users ----
CREATE TABLE users (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    VARCHAR(80)  NOT NULL,
    email                   VARCHAR(160) NOT NULL,
    password_hash           VARCHAR(100) NOT NULL,
    role                    VARCHAR(16)  NOT NULL DEFAULT 'USER',
    timezone                VARCHAR(64)  NOT NULL DEFAULT 'UTC',
    email_reminders_enabled BOOLEAN      NOT NULL DEFAULT FALSE,
    enabled                 BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE INDEX ix_users_role ON users (role);

-- ------------------------------------------------------ job_applications ----
CREATE TABLE job_applications (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT        NOT NULL,
    company             VARCHAR(140)  NOT NULL,
    job_title           VARCHAR(160)  NOT NULL,
    job_description     TEXT,
    job_url             VARCHAR(500),
    source              VARCHAR(60),
    employment_type     VARCHAR(24)   NOT NULL DEFAULT 'FULL_TIME',
    work_mode           VARCHAR(16)   NOT NULL DEFAULT 'ONSITE',
    location            VARCHAR(160),
    currency            VARCHAR(8)    NOT NULL DEFAULT 'INR',
    expected_salary_min NUMERIC(14, 2),
    expected_salary_max NUMERIC(14, 2),
    status              VARCHAR(20)   NOT NULL DEFAULT 'SAVED',
    applied_at          DATE,
    deadline            DATE,
    next_action_date    DATE,
    next_action         VARCHAR(200),
    notes               TEXT,
    first_response_at   TIMESTAMPTZ,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_applications_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_applications_status CHECK (status IN
        ('SAVED', 'APPLIED', 'ASSESSMENT', 'INTERVIEW', 'OFFER', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT ck_applications_employment_type CHECK (employment_type IN
        ('FULL_TIME', 'PART_TIME', 'INTERNSHIP', 'CONTRACT', 'FREELANCE', 'TEMPORARY')),
    CONSTRAINT ck_applications_work_mode CHECK (work_mode IN ('ONSITE', 'HYBRID', 'REMOTE')),
    CONSTRAINT ck_applications_salary_range CHECK
        (expected_salary_min IS NULL OR expected_salary_max IS NULL
            OR expected_salary_min <= expected_salary_max)
);

-- Composite indexes for the ownership-scoped list / filter / sort queries.
CREATE INDEX ix_applications_user_status        ON job_applications (user_id, status);
CREATE INDEX ix_applications_user_applied_at    ON job_applications (user_id, applied_at DESC);
CREATE INDEX ix_applications_user_deadline      ON job_applications (user_id, deadline);
CREATE INDEX ix_applications_user_next_action   ON job_applications (user_id, next_action_date);
CREATE INDEX ix_applications_user_created_at    ON job_applications (user_id, created_at DESC);
CREATE INDEX ix_applications_employment_type    ON job_applications (user_id, employment_type);
-- Functional indexes backing case-insensitive company / title search.
CREATE INDEX ix_applications_company_lower      ON job_applications (lower(company));
CREATE INDEX ix_applications_job_title_lower    ON job_applications (lower(job_title));

-- ------------------------------------------------------------ app tags ----
-- Mapped as a JPA @ElementCollection: a plain normalised child table whose
-- primary key is the (application_id, tag) pair.
CREATE TABLE application_tags (
    application_id  BIGINT       NOT NULL,
    tag             VARCHAR(40)  NOT NULL,
    CONSTRAINT fk_tags_application
        FOREIGN KEY (application_id) REFERENCES job_applications (id) ON DELETE CASCADE,
    CONSTRAINT pk_application_tags PRIMARY KEY (application_id, tag)
);

CREATE INDEX ix_tags_tag ON application_tags (lower(tag));

-- ------------------------------------------------------------- interviews ----
CREATE TABLE interviews (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id   BIGINT       NOT NULL,
    round_type       VARCHAR(24)  NOT NULL,
    scheduled_at     TIMESTAMPTZ  NOT NULL,
    duration_minutes INT          NOT NULL DEFAULT 45,
    location_or_link VARCHAR(500),
    interviewer_name VARCHAR(140),
    prep_notes       TEXT,
    feedback         TEXT,
    outcome          VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_interviews_application
        FOREIGN KEY (application_id) REFERENCES job_applications (id) ON DELETE CASCADE,
    CONSTRAINT ck_interviews_round_type CHECK (round_type IN
        ('RECRUITER_CALL', 'PHONE_SCREEN', 'CODING_ASSESSMENT', 'TECHNICAL',
         'SYSTEM_DESIGN', 'HR', 'FINAL', 'ON_SITE')),
    CONSTRAINT ck_interviews_outcome CHECK (outcome IN
        ('PENDING', 'PASSED', 'FAILED', 'RESCHEDULED', 'CANCELLED')),
    CONSTRAINT ck_interviews_duration CHECK (duration_minutes > 0 AND duration_minutes <= 720)
);

CREATE INDEX ix_interviews_application            ON interviews (application_id);
CREATE INDEX ix_interviews_scheduled_at           ON interviews (scheduled_at);
CREATE INDEX ix_interviews_app_scheduled          ON interviews (application_id, scheduled_at);

-- -------------------------------------------------------------- reminders ----
CREATE TABLE reminders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL,
    application_id  BIGINT,
    type            VARCHAR(28)   NOT NULL,
    source          VARCHAR(24)   NOT NULL DEFAULT 'MANUAL',
    title           VARCHAR(200)  NOT NULL,
    details         VARCHAR(500),
    due_at          TIMESTAMPTZ   NOT NULL,
    dedupe_key      VARCHAR(200),
    completed_at    TIMESTAMPTZ,
    notified_at     TIMESTAMPTZ,
    email_sent_at   TIMESTAMPTZ,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_reminders_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_reminders_application
        FOREIGN KEY (application_id) REFERENCES job_applications (id) ON DELETE CASCADE,
    CONSTRAINT ck_reminders_type CHECK (type IN
        ('APPLICATION_DEADLINE', 'FOLLOW_UP', 'INTERVIEW_PREP', 'NEXT_ACTION', 'CUSTOM')),
    CONSTRAINT ck_reminders_source CHECK (source IN ('MANUAL', 'AUTO'))
);

CREATE INDEX ix_reminders_user_due       ON reminders (user_id, due_at);
CREATE INDEX ix_reminders_user_open      ON reminders (user_id, completed_at);
CREATE INDEX ix_reminders_application    ON reminders (application_id);
-- Duplicate prevention for the scheduler: one *open* auto-reminder per key.
CREATE UNIQUE INDEX ux_reminders_open_dedupe
    ON reminders (user_id, dedupe_key)
    WHERE completed_at IS NULL AND dedupe_key IS NOT NULL;

-- ------------------------------------------- application_status_history ----
CREATE TABLE application_status_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id  BIGINT       NOT NULL,
    from_status     VARCHAR(20),
    to_status       VARCHAR(20)  NOT NULL,
    note            VARCHAR(400),
    changed_by      BIGINT,
    changed_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_history_application
        FOREIGN KEY (application_id) REFERENCES job_applications (id) ON DELETE CASCADE,
    CONSTRAINT fk_history_changed_by
        FOREIGN KEY (changed_by) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX ix_history_application ON application_status_history (application_id, changed_at);

-- --------------------------------------------------------- refresh_tokens ----
CREATE TABLE refresh_tokens (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT        NOT NULL,
    token_hash             VARCHAR(64)   NOT NULL,
    family_id              UUID          NOT NULL,
    expires_at             TIMESTAMPTZ   NOT NULL,
    revoked_at             TIMESTAMPTZ,
    replaced_by_token_hash VARCHAR(64),
    user_agent             VARCHAR(255),
    ip_address             VARCHAR(64),
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_refresh_token_hash UNIQUE (token_hash)
);

CREATE INDEX ix_refresh_tokens_user   ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX ix_refresh_tokens_expiry ON refresh_tokens (expires_at);
